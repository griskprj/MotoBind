### Замена масла в двигателе (Легко)

**Описание:**
Регламентная процедура замены моторного масла и масляного фильтра для двигателей объемом от 500 до 1000 см³.

**Необходимые материалы:**
- Моторное масло (10W-40, API SN) — 3.5 литра;
- Масляный фильтр — оригинальный или аналог;
- Медная шайба сливной пробки;
- Ключ для сливной пробки (на 17);
- Съемник масляного фильтра.

**Пошаговая инструкция:**

**Шаг 1. Прогрев двигателя**
Запустите двигатель и дайте ему поработать на холостых оборотах 5-7 минут до рабочей температуры (около 90°C). Прогретое масло имеет меньшую вязкость и лучше сливается.

**Шаг 2. Слив старого масла**
Установите мотоцикл на центральную подставку. Подставьте емкость под сливную пробку. Открутите пробку и дайте маслу стечь (минимум 15 минут).

**Шаг 3. Замена масляного фильтра**
Используйте съемник для откручивания старого фильтра. Смажьте новое уплотнительное кольцо свежим маслом. Установите новый фильтр рукой.

**Техника безопасности:**
> ⚠️ Работайте с горячим маслом осторожно — используйте термостойкие перчатки.
